package com.maplehush.admin.modules.system.auth.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.maplehush.admin.modules.system.auth.config.PasswordConfiguration;
import com.maplehush.admin.modules.system.auth.mapper.AuthUserMapper;
import com.maplehush.admin.modules.system.auth.service.impl.BootstrapAdminServiceImpl;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.security.crypto.password.PasswordEncoder;

class BootstrapAdminServiceTest {

    private JdbcTemplate jdbc;
    private PasswordEncoder encoder;
    private IBootstrapAdminService service;

    @BeforeEach
    void setUp() throws Exception {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:bootstrap_" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE sys_role (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  role_code VARCHAR(64) NOT NULL UNIQUE,
                  status TINYINT NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE sys_user (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  username VARCHAR(64) NOT NULL UNIQUE,
                  password_hash VARCHAR(255) NOT NULL,
                  real_name VARCHAR(128) NOT NULL,
                  status TINYINT NOT NULL,
                  must_change_password TINYINT NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE sys_user_role (
                  user_id BIGINT NOT NULL,
                  role_id BIGINT NOT NULL,
                  PRIMARY KEY (user_id, role_id)
                )
                """);
        jdbc.update("INSERT INTO sys_role (role_code, status) VALUES (?, 1)", "super_admin");
        encoder = new PasswordConfiguration().passwordEncoder();
        service = new BootstrapAdminServiceImpl(
                TestMapperFactory.create(dataSource).getMapper(AuthUserMapper.class),
                encoder,
                new DataSourceTransactionManager(dataSource));
    }

    @Test
    void createsOneAdministratorWithHashedPasswordAndRequiredPasswordChange() {
        long userId = service.createFirstAdmin("admin");

        String hash = jdbc.queryForObject("SELECT password_hash FROM sys_user WHERE id = ?", String.class, userId);
        assertFalse("12345678".equals(hash));
        assertTrue(hash.startsWith("{pbkdf2@SpringSecurity_v5_8}"));
        assertTrue(encoder.matches("12345678", hash));
        assertEquals(
                1,
                jdbc.queryForObject("SELECT must_change_password FROM sys_user WHERE id = ?", Integer.class, userId));
        assertEquals(1, jdbc.queryForObject("""
                SELECT COUNT(*) FROM sys_user_role ur
                JOIN sys_role r ON r.id = ur.role_id
                WHERE ur.user_id = ? AND r.role_code = 'super_admin'
                """, Integer.class, userId));
    }

    @Test
    void repeatedBootstrapCannotReplacePasswordOrCreateAnotherUser() {
        service.createFirstAdmin("admin");
        String originalHash =
                jdbc.queryForObject("SELECT password_hash FROM sys_user WHERE username = 'admin'", String.class);

        assertThrows(IllegalStateException.class, () -> service.createFirstAdmin("second"));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM sys_user", Integer.class));
        assertEquals(
                originalHash,
                jdbc.queryForObject("SELECT password_hash FROM sys_user WHERE username = 'admin'", String.class));
    }

    @Test
    void automaticBootstrapCreatesOnlyForAnEmptyDatabase() {
        Long userId = service.createFirstAdminIfEmpty("admin");
        String originalHash =
                jdbc.queryForObject("SELECT password_hash FROM sys_user WHERE id = ?", String.class, userId);

        assertNull(service.createFirstAdminIfEmpty("second"));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM sys_user", Integer.class));
        assertEquals(
                originalHash,
                jdbc.queryForObject("SELECT password_hash FROM sys_user WHERE id = ?", String.class, userId));
    }

    @Test
    void invalidInputDoesNotCreateAUser() {
        assertThrows(IllegalArgumentException.class, () -> service.createFirstAdmin("a"));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM sys_user", Integer.class));
    }

    @Test
    void failedRoleAssignmentRollsBackUserCreation() {
        jdbc.execute("DROP TABLE sys_user_role");

        assertThrows(RuntimeException.class, () -> service.createFirstAdmin("admin"));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM sys_user", Integer.class));
    }
}
