-- 业务时间统一到秒；历史毫秒向下截断，避免 ALTER 时将 .500 以上四舍五入到下一秒。
-- 旧版迁移保持原样；新库也会在执行完 V1-V10 后应用本迁移。
SET SESSION sql_mode = CONCAT_WS(',', NULLIF(@@sql_mode, ''), 'TIME_TRUNCATE_FRACTIONAL');

ALTER TABLE sys_dept
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_user
    MODIFY COLUMN password_change_time DATETIME NULL,
    MODIFY COLUMN last_login_time DATETIME NULL,
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_role
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_user_role
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE sys_menu
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_permission
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE sys_role_menu
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE sys_role_permission
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE sys_session
    MODIFY COLUMN expire_time DATETIME NOT NULL,
    MODIFY COLUMN revoke_time DATETIME NULL,
    MODIFY COLUMN create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE sys_login_log
    MODIFY COLUMN occur_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

ALTER TABLE sys_operation_log
    MODIFY COLUMN occur_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;
